import {
  CreateIssueCommentResponseSchema,
  CreateIssueCommentSchema,
  DeleteIssueCommentResponseSchema,
  GetIssueActivitiesQuerySchema,
  GetIssueActivitiesResponseSchema,
  GetIssueAssigneesResponseSchema,
  GetIssueEvaluationsQuerySchema,
  GetIssueEvaluationsResponseSchema,
  GetIssueOccurrencesQuerySchema,
  GetIssueOccurrencesResponseSchema,
  GetIssueRecordsQuerySchema,
  GetIssueRecordsResponseSchema,
  GetIssueResponseSchema,
  GetIssuesQuerySchema,
  GetIssuesResponseSchema,
  GetIssuesSummaryQuerySchema,
  GetIssuesSummaryResponseSchema,
  IssueIdParamsSchema,
  IssueCommentIdParamsSchema,
  UpdateIssueAssigneesResponseSchema,
  UpdateIssueAssigneesSchema,
  UpdateIssueCommentResponseSchema,
  UpdateIssueCommentSchema,
  UpdateIssueStatusResponseSchema,
  UpdateIssueStatusSchema,
  WorkspaceIdParamsSchema,
} from "@repo/dto";
import { defineEndpoint } from "./util/endpoint.js";

export const ISSUES_BASE_PATH = "/workspace";

export const issuesContract = {
  basePath: ISSUES_BASE_PATH,
  getIssueRecords: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/issue-records",
    params: WorkspaceIdParamsSchema,
    request: GetIssueRecordsQuerySchema,
    response: GetIssueRecordsResponseSchema,
  }),
  getIssues: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/issues",
    params: WorkspaceIdParamsSchema,
    request: GetIssuesQuerySchema,
    response: GetIssuesResponseSchema,
  }),
  getSummary: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/issues/summary",
    params: WorkspaceIdParamsSchema,
    request: GetIssuesSummaryQuerySchema,
    response: GetIssuesSummaryResponseSchema,
  }),
  getIssue: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/issues/:issueId",
    params: IssueIdParamsSchema,
    request: null,
    response: GetIssueResponseSchema,
  }),
  getOccurrences: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/issues/:issueId/occurrences",
    params: IssueIdParamsSchema,
    request: GetIssueOccurrencesQuerySchema,
    response: GetIssueOccurrencesResponseSchema,
  }),
  getEvaluations: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/issues/:issueId/evaluations",
    params: IssueIdParamsSchema,
    request: GetIssueEvaluationsQuerySchema,
    response: GetIssueEvaluationsResponseSchema,
  }),
  getActivities: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/issues/:issueId/activities",
    params: IssueIdParamsSchema,
    request: GetIssueActivitiesQuerySchema,
    response: GetIssueActivitiesResponseSchema,
  }),
  createComment: defineEndpoint({
    method: "POST",
    path: "/:workspaceId/issues/:issueId/comments",
    params: IssueIdParamsSchema,
    request: CreateIssueCommentSchema,
    response: CreateIssueCommentResponseSchema,
  }),
  updateComment: defineEndpoint({
    method: "PATCH",
    path: "/:workspaceId/issues/:issueId/comments/:commentId",
    params: IssueCommentIdParamsSchema,
    request: UpdateIssueCommentSchema,
    response: UpdateIssueCommentResponseSchema,
  }),
  deleteComment: defineEndpoint({
    method: "DELETE",
    path: "/:workspaceId/issues/:issueId/comments/:commentId",
    params: IssueCommentIdParamsSchema,
    request: null,
    response: DeleteIssueCommentResponseSchema,
  }),
  getAssignees: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/issues/:issueId/assignees",
    params: IssueIdParamsSchema,
    request: null,
    response: GetIssueAssigneesResponseSchema,
  }),
  updateAssignees: defineEndpoint({
    method: "PATCH",
    path: "/:workspaceId/issues/:issueId/assignees",
    params: IssueIdParamsSchema,
    request: UpdateIssueAssigneesSchema,
    response: UpdateIssueAssigneesResponseSchema,
  }),
  updateStatus: defineEndpoint({
    method: "PATCH",
    path: "/:workspaceId/issues/:issueId/status",
    params: IssueIdParamsSchema,
    request: UpdateIssueStatusSchema,
    response: UpdateIssueStatusResponseSchema,
  }),
};
