import {
  ComparePromptVersionsQuerySchema,
  CreatePromptExperimentSchema,
  CreatePromptSchema,
  CreatePromptVersionSchema,
  DeployPromptSchema,
  PromptDeleteResponseSchema,
  PromptDeploymentListResponseSchema,
  PromptDeploymentResponseSchema,
  PromptExperimentIdParamsSchema,
  PromptExperimentListResponseSchema,
  PromptExperimentResponseSchema,
  PromptIdParamsSchema,
  PromptListResponseSchema,
  PromptMutationResponseSchema,
  PromptResponseSchema,
  PromptVersionDiffResponseSchema,
  PromptVersionIdParamsSchema,
  PromptVersionListResponseSchema,
  PromptVersionMetricsQuerySchema,
  PromptVersionMetricsResponseSchema,
  PromptVersionResponseSchema,
  RollbackPromptSchema,
  UpdatePromptExperimentStatusSchema,
  UpdatePromptSchema,
  WorkspaceIdParamsSchema,
} from "@repo/dto";
import { defineEndpoint } from "./util/endpoint.js";

export const promptContract = {
  basePath: "/workspace",
  list: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/prompts",
    params: WorkspaceIdParamsSchema,
    request: null,
    response: PromptListResponseSchema,
  }),
  get: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/prompts/:promptId",
    params: PromptIdParamsSchema,
    request: null,
    response: PromptResponseSchema,
  }),
  create: defineEndpoint({
    method: "POST",
    path: "/:workspaceId/prompts",
    params: WorkspaceIdParamsSchema,
    request: CreatePromptSchema,
    response: PromptMutationResponseSchema,
  }),
  update: defineEndpoint({
    method: "PATCH",
    path: "/:workspaceId/prompts/:promptId",
    params: PromptIdParamsSchema,
    request: UpdatePromptSchema,
    response: PromptMutationResponseSchema,
  }),
  delete: defineEndpoint({
    method: "DELETE",
    path: "/:workspaceId/prompts/:promptId",
    params: PromptIdParamsSchema,
    request: null,
    response: PromptDeleteResponseSchema,
  }),
  createVersion: defineEndpoint({
    method: "POST",
    path: "/:workspaceId/prompts/:promptId/versions",
    params: PromptIdParamsSchema,
    request: CreatePromptVersionSchema,
    response: PromptVersionResponseSchema,
  }),
  listVersions: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/prompts/:promptId/versions",
    params: PromptIdParamsSchema,
    request: null,
    response: PromptVersionListResponseSchema,
  }),
  compareVersions: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/prompts/:promptId/versions/compare",
    params: PromptIdParamsSchema,
    request: ComparePromptVersionsQuerySchema,
    response: PromptVersionDiffResponseSchema,
  }),
  getVersionMetrics: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/prompts/:promptId/versions/:versionId/metrics",
    params: PromptVersionIdParamsSchema,
    request: PromptVersionMetricsQuerySchema,
    response: PromptVersionMetricsResponseSchema,
  }),
  deploy: defineEndpoint({
    method: "POST",
    path: "/:workspaceId/prompts/:promptId/deployments",
    params: PromptIdParamsSchema,
    request: DeployPromptSchema,
    response: PromptDeploymentResponseSchema,
  }),
  rollback: defineEndpoint({
    method: "POST",
    path: "/:workspaceId/prompts/:promptId/rollback",
    params: PromptIdParamsSchema,
    request: RollbackPromptSchema,
    response: PromptDeploymentResponseSchema,
  }),
  listDeployments: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/prompts/:promptId/deployments",
    params: PromptIdParamsSchema,
    request: null,
    response: PromptDeploymentListResponseSchema,
  }),
  createExperiment: defineEndpoint({
    method: "POST",
    path: "/:workspaceId/prompts/:promptId/experiments",
    params: PromptIdParamsSchema,
    request: CreatePromptExperimentSchema,
    response: PromptExperimentResponseSchema,
  }),
  listExperiments: defineEndpoint({
    method: "GET",
    path: "/:workspaceId/prompts/:promptId/experiments",
    params: PromptIdParamsSchema,
    request: null,
    response: PromptExperimentListResponseSchema,
  }),
  updateExperimentStatus: defineEndpoint({
    method: "PATCH",
    path: "/:workspaceId/prompts/:promptId/experiments/:experimentId/status",
    params: PromptExperimentIdParamsSchema,
    request: UpdatePromptExperimentStatusSchema,
    response: PromptExperimentResponseSchema,
  }),
};
